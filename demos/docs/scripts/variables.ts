// Generates the data of the Reference's CSS Variables page from the compiled
// core.css (PORT-PLAN.md, Phase 17), before `ng build` / `ng serve`:
//
//   demos/docs/.generated/variables.ts
//
// which src/app/packages/pages/variables.component.ts imports. The page has no
// list of its own: a token added to core appears on it at the next build, and
// one that fits nowhere on the page stops the build (lib/variables.ts).
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { repoRoot } from '../../../packages/theme-core/test/lib/sass.ts';
import { variablesData } from './lib/variables.ts';

const out = path.resolve(import.meta.dirname, '../.generated/variables.ts');
const data = variablesData();
mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(
  out,
  [
    '// Generated by demos/docs/scripts/variables.ts from the compiled core.css. Do not edit.',
    "import type { VariablesData } from '../src/app/packages/pages/variables/variables-data';",
    '',
    `export const VARIABLES: VariablesData = ${JSON.stringify(data, null, 2)};`,
    '',
  ].join('\n'),
);
console.log(
  `variables: ${data.colourTokens} colour tokens in ${data.palettes.length} palettes, ` +
    `${data.otherVariables} other variables; written to ${path.relative(repoRoot, out)}`,
);
